# CI only: stand-ins for the owner's extracted vendor files, so a tree without them builds.
#   tools/ci-blob-stubs.sh <aosp-tree>
# CI cannot have the PowerVR libraries (they come only from the owner's image). The only build
# step that needs them is hardware/ti/omap4's pvrsrvinit, which links libsrv_init_SGX540_120 and
# libsrv_um_SGX540_120 from /system/vendor/lib. This writes vendor/glass/glass-1/ with two empty
# libraries of those names (libsrv_init exports a SrvInit that does nothing) and sets
# ro.glass.blob_stubs=true. An image built with them has no GPU user space and must never be
# booted. The owner's build replaces this directory with extract_vendor.py's output.
set -eu

if [ $# -ne 1 ]; then
    echo "usage: $0 <aosp-tree>" >&2
    exit 2
fi
dir=$1/vendor/glass/glass-1
if [ -e "$dir/proprietary" ]; then
    echo "error: $dir/proprietary exists (extracted files); not overwriting with stubs" >&2
    exit 1
fi
mkdir -p "$dir"

cat > "$dir/device-vendor.mk" <<'EOM'
# Generated by OpenMyGlass/manifest tools/ci-blob-stubs.sh: CI stand-ins, not a bootable vendor.
PRODUCT_PACKAGES += libsrv_init_SGX540_120 libsrv_um_SGX540_120
PRODUCT_PROPERTY_OVERRIDES += ro.glass.blob_stubs=true
EOM

cat > "$dir/stub.c" <<'EOM'
/* Generated by OpenMyGlass/manifest tools/ci-blob-stubs.sh: CI stand-in, does nothing. */
int SrvInit(int x);
int SrvInit(int x) { (void) x; return 0; }
EOM
: > "$dir/empty.c"

cat > "$dir/Android.mk" <<'EOM'
# Generated by OpenMyGlass/manifest tools/ci-blob-stubs.sh: CI stand-ins, not a bootable vendor.
LOCAL_PATH := $(call my-dir)

include $(CLEAR_VARS)
LOCAL_MODULE := libsrv_init_SGX540_120
LOCAL_MODULE_TAGS := optional
LOCAL_SRC_FILES := stub.c
LOCAL_MODULE_PATH := $(TARGET_OUT_VENDOR)/lib
include $(BUILD_SHARED_LIBRARY)

include $(CLEAR_VARS)
LOCAL_MODULE := libsrv_um_SGX540_120
LOCAL_MODULE_TAGS := optional
LOCAL_SRC_FILES := empty.c
LOCAL_MODULE_PATH := $(TARGET_OUT_VENDOR)/lib
include $(BUILD_SHARED_LIBRARY)

# pvrsrvinit links these with -L$(TARGET_OUT_VENDOR)/lib: make the link wait for them.
$(call intermediates-dir-for,EXECUTABLES,pvrsrvinit)/LINKED/pvrsrvinit: \
    $(TARGET_OUT_VENDOR)/lib/libsrv_init_SGX540_120.so \
    $(TARGET_OUT_VENDOR)/lib/libsrv_um_SGX540_120.so
EOM
echo "CI stubs: $dir (ro.glass.blob_stubs=true; never boot this image)"
