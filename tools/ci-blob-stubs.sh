#!/bin/sh
# shellcheck disable=SC2016,SC1003  # make syntax written out in single quotes
# SPDX-License-Identifier: Apache-2.0
# CI only: stand-ins for the owner's extracted vendor files, so a tree without them builds.
#   tools/ci-blob-stubs.sh <aosp-tree> [4.4|6.0]
# CI cannot have the PowerVR libraries (they come only from the owner's image). The build steps
# that need them are in hardware/ti/omap4, and link from /system/vendor/lib:
#   4.4 (omap4-aosp aosp-4.4): pvrsrvinit links libsrv_init_SGX540_120 and libsrv_um_SGX540_120;
#   6.0 (omap4-aosp stable): pvrsrvinit links libsrv_init and libsrv_um, and the open EGL
#       wrapper libEGL_POWERVR_SGX54X links libIMGegl (the generic names, symlinks to the
#       _SGX540_120 files on a device) and calls its IMGegl* functions.
# This writes vendor/glass/glass-1/ with libraries of those names that do nothing: libsrv_init
# exports a SrvInit, libIMGegl every IMGegl* function egl.c calls. It also sets
# ro.glass.blob_stubs=true. An image built with them has no GPU user space and must never be
# booted. The owner's build replaces this directory with extract_vendor.py's output.
set -eu

if [ $# -lt 1 ] || [ $# -gt 2 ]; then
    echo "usage: $0 <aosp-tree> [4.4|6.0]" >&2
    exit 2
fi
android=${2:-4.4}
case $android in
    4.4) srv_init=libsrv_init_SGX540_120 srv_um=libsrv_um_SGX540_120 ;;
    6.0) srv_init=libsrv_init srv_um=libsrv_um
         egl_c=$1/hardware/ti/omap4/libEGL_POWERVR/egl.c
         [ -f "$egl_c" ] || { echo "error: no $egl_c (run repo sync first)" >&2; exit 1; }
         egl_syms=$(grep -o 'IMGegl[A-Za-z0-9_]*' "$egl_c" | sort -u)
         [ -n "$egl_syms" ] || { echo "error: no IMGegl calls in $egl_c" >&2; exit 1; } ;;
    *) echo "error: unknown Android version $android (4.4 or 6.0)" >&2; exit 2 ;;
esac
dir=$1/vendor/glass/glass-1
if [ -e "$dir/proprietary" ]; then
    echo "error: $dir/proprietary exists (extracted files); not overwriting with stubs" >&2
    exit 1
fi
mkdir -p "$dir"

packages="$srv_init $srv_um"
[ "$android" = 4.4 ] || packages="$packages libIMGegl"
cat > "$dir/device-vendor.mk" <<EOM
# Generated by OpenMyGlass/manifest tools/ci-blob-stubs.sh: CI stand-ins, not a bootable vendor.
PRODUCT_PACKAGES += $packages
PRODUCT_PROPERTY_OVERRIDES += ro.glass.blob_stubs=true
EOM

cat > "$dir/stub.c" <<'EOM'
/* Generated by OpenMyGlass/manifest tools/ci-blob-stubs.sh: CI stand-in, does nothing. */
int SrvInit(int x);
int SrvInit(int x) { (void) x; return 0; }
EOM
: > "$dir/empty.c"

lib() {
    # lib <module> <source>: a stub shared library installed in /system/vendor/lib.
    cat <<EOM

include \$(CLEAR_VARS)
LOCAL_MODULE := $1
LOCAL_MODULE_TAGS := optional
LOCAL_SRC_FILES := $2
LOCAL_MODULE_PATH := \$(TARGET_OUT_VENDOR)/lib
include \$(BUILD_SHARED_LIBRARY)
EOM
}
{
    echo '# Generated by OpenMyGlass/manifest tools/ci-blob-stubs.sh: CI stand-ins, not a bootable vendor.'
    echo 'LOCAL_PATH := $(call my-dir)'
    lib "$srv_init" stub.c
    lib "$srv_um" empty.c
    echo
    echo '# pvrsrvinit links these with -L$(TARGET_OUT_VENDOR)/lib: make the link wait for them.'
    echo '$(call intermediates-dir-for,EXECUTABLES,pvrsrvinit)/LINKED/pvrsrvinit: \'
    echo "    \$(TARGET_OUT_VENDOR)/lib/$srv_init.so \\"
    echo "    \$(TARGET_OUT_VENDOR)/lib/$srv_um.so"
    if [ "$android" = 6.0 ]; then
        lib libIMGegl egl_stub.c
        echo
        echo '# libEGL_POWERVR_SGX54X links it with -L$(TARGET_OUT_VENDOR)/lib: make the link wait for it.'
        echo '$(call intermediates-dir-for,SHARED_LIBRARIES,libEGL_POWERVR_SGX54X)/LINKED/libEGL_POWERVR_SGX54X.so: \'
        echo '    $(TARGET_OUT_VENDOR)/lib/libIMGegl.so'
    fi
} > "$dir/Android.mk"
if [ "$android" = 6.0 ]; then
    {
        echo '/* Generated by OpenMyGlass/manifest tools/ci-blob-stubs.sh: CI stand-in, does nothing.'
        echo '   One symbol for each IMGegl* function hardware/ti/omap4/libEGL_POWERVR/egl.c calls. */'
        for f in $egl_syms; do
            echo "void $f(void);"
            echo "void $f(void) {}"
        done
    } > "$dir/egl_stub.c"
fi
echo "CI stubs ($android): $dir (ro.glass.blob_stubs=true; never boot this image)"
